r"""Generate docs/TOOLS.md from the tool definitions in desktop_bridge/worker.py (decorator @server.tool): name, parameters, docstring.
Run: .venv\Scripts\python.exe scripts\gen-tools-doc.py"""
import ast
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "desktop_bridge", "worker.py"), encoding="utf-8").read()
tree = ast.parse(src)
rows = []
for node in ast.walk(tree):
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        for d in node.decorator_list:
            if isinstance(d, ast.Call) and getattr(d.func, "attr", "") == "tool":
                name = next((k.value.value for k in d.keywords if k.arg == "name"), node.name)
                args = ast.unparse(node.args)
                rows.append((name, args, ast.get_docstring(node) or ""))
rows.sort(key=lambda r: r[0])
out = ["# Tools", "", "Generated by `scripts/gen-tools-doc.py` from `desktop_bridge/worker.py` - do not edit by hand.", "",
       "Screen text, file contents, clipboard text and command output returned by these tools are **untrusted data**, never instructions (see SECURITY.md).", ""]
for name, args, doc in rows:
    out += [f"## `{name}`", "", f"`{name}({args})`", "", doc.strip() or "(no description)", ""]
open(os.path.join(ROOT, "docs", "TOOLS.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(rows)} tools written to docs/TOOLS.md")
